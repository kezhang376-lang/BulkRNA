# 额外的阳性GO绘图探针；给已部署包和新的独立输出目录，不改生产配置。
args <- commandArgs(trailingOnly = TRUE)
bundle <- normalizePath(args[1], mustWork = TRUE)
probe <- args[2]
source(file.path(bundle, "code/R/common.R"))
source(file.path(bundle, "code/R/enrichment.R"))
source(file.path(bundle, "code/R/custom_plots.R"))
runtime <- read_json(file.path(bundle, "runtime.json"))
verify_pod_account(runtime$config$kubernetes$account)
need(c("AnnotationDbi", runtime$config$enrichment$orgdb))
if (file.exists(probe) || !dir.create(probe, recursive = TRUE)) stopf("Probe output already exists")
db <- getExportedValue(runtime$config$enrichment$orgdb, runtime$config$enrichment$orgdb)
set.seed(19)
ids <- sample(AnnotationDbi::keys(db, keytype = "ENSEMBL"), 1000)
mapping <- AnnotationDbi::select(db, keys = ids, keytype = "ENSEMBL", columns = c("GOALL", "ONTOLOGYALL"))
mapping <- unique(mapping[!is.na(mapping$GOALL) & !is.na(mapping$ONTOLOGYALL) & mapping$ONTOLOGYALL == "BP", c("ENSEMBL", "GOALL")])
sizes <- table(mapping$GOALL)
target <- names(sizes[sizes >= 15 & sizes <= 30])[1]
if (is.na(target)) stopf("No suitable synthetic target GO set")
genes <- unique(mapping$ENSEMBL[mapping$GOALL == target])
scores <- rnorm(length(ids))
scores[ids %in% genes] <- 5 + runif(sum(ids %in% genes))
tab <- data.frame(gene_id = ids, log2FoldChange = scores, stat = scores, pvalue = 0.5, padj = 0.5, regulated = "normal")
tab$padj[ids %in% genes] <- 0.001
tab$regulated[ids %in% genes] <- "up"
dir.create(file.path(probe, "de", "synthetic_positive"), recursive = TRUE)
write.csv(tab, file.path(probe, "de/synthetic_positive/all_genes.csv"), row.names = FALSE)
run_enrichment(data.frame(contrast_id = "synthetic_positive"), runtime, file.path(probe, "de"), file.path(probe, "out"))
folder <- file.path(probe, "out/synthetic_positive")
if (!file.exists(file.path(folder, "go_ora_up_dotplot.pdf")) || !file.exists(file.path(folder, "go_gsea_dotplot.pdf"))) stopf("Positive GO dotplots missing")
plot_target_go(file.path(folder, "go_gsea.rds"), target, file.path(probe, "target_go"))
if (!any(grepl("[.]pdf$", list.files(file.path(probe, "target_go"))))) stopf("Target GO curve missing")
write_json(list(status = "succeeded", kind = "synthetic_positive_only", target_go = target), file.path(probe, "status.json"))
cat("GO_POSITIVE_PLOT_COMPATIBILITY_PASS\n")
